export type Language = "en" | "fr" | "es" | "pt" | "ar" | "hi" | "zh"
export type LanguagePreference = Language | "system"
export type TextDirection = "ltr" | "rtl"

export type LanguageOption = {
  code: Language
  label: string
  nativeLabel: string
  direction: TextDirection
  aliases: string[]
}

